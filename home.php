            <ul>
                <li>Students interested in participating in the internship program submit their applications.</li>
                <li>Applications include a student profile and letter of academic grading score recommended by student affairs department.</li>
            </ul>
        </div>
		<div data-aos="zoom-in-up" data-aos-delay="50" data-aos-duration="1000" style="background-color: #00a2d1; padding: 20px;border-radius: 30px;color:white;">
