			<ul>
				<li>Interns attend an orientation session to learn about the expectations, policies, and guidelines of the internship program.</li>
				<li>This orientation will cover topics such as workplace etiquette, dress code, communication protocols, and safety regulations.</li>
			</ul>
        </div>
		<div data-aos="zoom-in-up" data-aos-delay="50" data-aos-duration="1000" style="background-color: #00a2d1; padding: 20px;border-radius: 30px;color:white;">
