			<ul>
				<li>Employers review applications and conduct interviews to select suitable candidates.</li>
				<li>Some internship programs involve a matching process where the university helps pair students with suitable companies or organizations.</li>
			</ul>
        </div>
		<div data-aos="zoom-in-up" data-aos-delay="50" data-aos-duration="1000" style="background-color: #00a2d1; padding: 20px;border-radius: 30px;color:white;">
