			<ul>
				<li>Interns and employers may sign internship agreements or contracts outlining the terms and conditions of the internship.</li>
				<li>It may require the development of learning objectives to ensure that the internship aligns with the student's academic and career goals.</li>
			</ul>
        </div>
		<div data-aos="zoom-in-up" data-aos-delay="50" data-aos-duration="1000" style="background-color: #00a2d1; padding: 20px;border-radius: 30px;color:white;">
			<h2>6. Academic Supervision:</h2>
			<ul>
				<li>A faculty academic supervisor is assigned to monitor the progress of the internship.</li>
				<li>Regular (weekly) check-ins or evaluations are scheduled to discuss the intern's experiences and ensure alignment with academic goals.</li>
			</ul>
        </div>
		<div data-aos="zoom-in-up" data-aos-delay="50" data-aos-duration="1000" style="background-color: #00a2d1; padding: 20px;border-radius: 30px;color:white;">
			<h2>7. Workplace Integration:</h2>
			<ul>
				<li>Interns join the workplace and integrate into the daily activities of the organization.</li>
				<li>They may be assigned specific projects, tasks, or responsibilities relevant to their field of study.</li>
				<li>It may include professional development activities, such as workshops, seminars, or training sessions, to enhance the interns' skills and knowledge.</li>
			</ul>
        </div>
